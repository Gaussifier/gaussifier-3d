"""Build the planar (flat 3DGS) runtime directory for ``gaussifier_planar_infer``.

Input: a runtime export directory (the release assets ``planar_*_runtime``)
(``forward_map / setup / pre_render / head_step / update / final .pt2`` torch.export
programs and ``planar_runtime.json``). Output: the same six graphs AOTInductor-compiled
with this environment's torch (``<name>_aoti.pt2``, the version the C++ harness links)
plus ``planar_runtime.env``, the flat ``key value...`` constants the harness reads.
With ``--trt`` the FP16 backbone (``backbone_fp16.pt2``) and the FP16 correction UNet
(``head_fp16.pt2``) also become raw TensorRT engines (``backbone.engine``, ``head.engine``) that
the harness runs instead of the AOTI forward map and the UNet half of the head step, like the
2D production path. The head's input assembly then runs as the ``head_input`` AOTI graph.

    uv run python scripts/build_planar_runtime.py --export <runtime export dir> --out <dir>
"""

from __future__ import annotations

import argparse
import json
import shutil
import time
from pathlib import Path

GRAPHS = ("forward_map", "setup", "pre_render", "head_step", "update", "final")
OPTIONAL_GRAPHS = ("head_input",)  # newer exports: the head step without its UNet
CAMERA_FIELDS = (
    "w2c",
    "position",
    "width",
    "height",
    "focal_x",
    "focal_y",
    "center_x",
    "center_y",
    "near",
    "far",
)


def build_trt_engine(
    program_path: Path, out_dir: Path, name: str, outputs_expected: int, *, decompose: bool = False
) -> Path:
    """FP16 TensorRT engine of a one-input program, extracted as raw bytes for trt_direct.

    ``decompose`` lowers the program to core ATen ops first. TensorRT 10.16 cannot build the
    correction UNet (main plus auxiliary U-Net, GroupNorm) as one engine: its Myelin code
    generator fails on the fused auxiliary branch (NVRTC compilation failure, no
    implementation for the node). With GroupNorm decomposed into its reductions and
    elementwise ops the whole UNet builds as one engine.
    """
    import sys

    import torch
    import torch_tensorrt
    from torch.export.graph_signature import InputKind

    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "cpp_inference" / "scripts"))
    from extract_trt_engine import engine_bytes_from_state, engine_state

    program = torch.export.load(str(program_path))
    if decompose:
        program = program.run_decompositions()
    user_inputs = [
        spec.arg.name
        for spec in program.graph_signature.input_specs
        if spec.kind == InputKind.USER_INPUT
    ]
    if len(user_inputs) != 1:
        raise SystemExit(f"{program_path.name} has inputs {user_inputs}, expected one")
    node = next(n for n in program.graph.nodes if n.name == user_inputs[0])
    shape = tuple(int(d) for d in node.meta["val"].shape)
    # One engine for the whole program: no torch fallback around it.
    compiled = torch_tensorrt.dynamo.compile(
        program,
        inputs=[torch_tensorrt.Input(shape, dtype=torch.float16)],
        require_full_compilation=True,
    )
    wrapper = out_dir / f"{name}_trt.pt"
    example = (torch.rand(*shape, device="cuda", dtype=torch.float16),)
    torch_tensorrt.save(compiled, str(wrapper), output_format="torchscript", arg_inputs=example)
    state = engine_state(wrapper)
    # The harness binds one input and the outputs in order.
    outputs = state[5].split("%") if isinstance(state[5], str) else list(state[5])
    if len(outputs) != outputs_expected:
        raise SystemExit(f"{name} engine has outputs {outputs}, expected {outputs_expected}")
    path = out_dir / f"{name}.engine"
    path.write_bytes(engine_bytes_from_state(state))
    return path


def write_env(
    meta: dict, path: Path, *, trt_backbone: bool = False, trt_head: bool = False
) -> None:
    """Flatten ``planar_runtime.json`` into ``key value...`` lines."""
    lines = ["# planar runtime constants (generated by scripts/build_planar_runtime.py)"]
    for key in ("height", "width", "iterations", "points_per_pixel_max", "render_n_max"):
        lines.append(f"{key} {meta[key]}")
    # 0 = the lean loop (render -> head -> update) of a model without gradient input.
    lines.append(f"gradient_input {1 if meta.get('gradient_input', True) else 0}")
    # 1 = run backbone.engine (TensorRT, FP16) and sum the count from its logits.
    lines.append(f"trt_backbone {1 if trt_backbone else 0}")
    # 1 = run head_input (AOTI) and head.engine (TensorRT, FP16) instead of head_step.
    lines.append(f"trt_head {1 if trt_head else 0}")
    lines.append(f"budget_scale {meta['budget_scale']}")
    for camera in ("frontal", "gradient_view"):
        for field in CAMERA_FIELDS:
            value = meta[camera][field]
            values = value if isinstance(value, list) else [value]
            lines.append(f"{camera}.{field} " + " ".join(repr(float(v)) for v in values))
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--export", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--trt", action="store_true", help="also build the TensorRT backbone")
    args = parser.parse_args()

    import torch
    from torch._inductor import aoti_compile_and_package

    args.out.mkdir(parents=True, exist_ok=True)
    meta = json.loads((args.export / "planar_runtime.json").read_text())
    missing = [name for name in GRAPHS if not (args.export / f"{name}.pt2").is_file()]
    if missing:
        raise SystemExit(f"export directory lacks {missing}")
    optional = [name for name in OPTIONAL_GRAPHS if (args.export / f"{name}.pt2").is_file()]
    for name in (*GRAPHS, *optional):
        start = time.perf_counter()
        program = torch.export.load(str(args.export / f"{name}.pt2"))
        aoti_compile_and_package(program, package_path=str(args.out / f"{name}_aoti.pt2"))
        seconds = time.perf_counter() - start
        print(f"{name:12s} compiled in {seconds:.1f} s (torch {torch.__version__})")
    trt_head = False
    if args.trt:
        # Backbone: logits plus the six maps. Head: the feature map.
        engines = [("backbone", "backbone_fp16.pt2", 7, False)]
        trt_head = "head_input" in optional and (args.export / "head_fp16.pt2").is_file()
        if trt_head:
            engines.append(("head", "head_fp16.pt2", 1, True))
        for name, program, outputs, decompose in engines:
            start = time.perf_counter()
            engine = build_trt_engine(
                args.export / program, args.out, name, outputs, decompose=decompose
            )
            print(
                f"{name:12s} TensorRT engine {engine.name} in {time.perf_counter() - start:.1f} s"
            )
    shutil.copyfile(args.export / "planar_runtime.json", args.out / "planar_runtime.json")
    write_env(meta, args.out / "planar_runtime.env", trt_backbone=args.trt, trt_head=trt_head)
    print(f"planar runtime ready in {args.out}")


if __name__ == "__main__":
    main()
